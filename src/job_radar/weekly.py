"""Weekly summary page in Notion: new matches (local first), what was applied to, and spend.

    python -m job_radar weekly [--write-notion] [--days 7]

No model calls — it reads the tracker and costs.csv only. The page is created under
NOTION_SUMMARY_PARENT_ID (default: Job Search Command Center). Without --write-notion it
prints the markdown (and writes reports/weekly_<date>.md).
"""
from __future__ import annotations

import calendar
import csv
import datetime as dt
from collections import Counter
from pathlib import Path

from .feedback import label_for_status, parse_notes
from .locality import LABELS, is_local, rank, tier_for


def spend(costs_path: Path, since: dt.date, until: dt.date) -> dict:
    """Sum costs.csv rows in [since, until] by label, plus month-to-date for `until`'s month."""
    week: Counter = Counter()
    mtd = 0.0
    runs = 0
    try:
        with costs_path.open() as f:
            for row in csv.DictReader(f):
                try:
                    day = dt.datetime.fromisoformat(row["timestamp"]).date()
                    usd = float(row["usd"])
                except (KeyError, ValueError):
                    continue
                if since <= day <= until:
                    week[row.get("label", "?")] += usd
                    runs += 1
                if day.year == until.year and day.month == until.month and day <= until:
                    mtd += usd
    except FileNotFoundError:
        pass
    return {"week_total": sum(week.values()), "by_label": dict(week), "runs": runs, "mtd": mtd}


def build(tracker, settings, today: dt.date | None = None, days: int = 7) -> tuple[str, list[str]]:
    """Return (title, lines) for the weekly page."""
    today = today or dt.date.today()
    since = today - dt.timedelta(days=days - 1)
    text, select = tracker.text, tracker.select
    priority = None
    try:
        import yaml
        priority = (yaml.safe_load(settings.companies_path.read_text()) or {}).get("location_priority")
    except Exception:
        pass

    new = []
    for r in tracker.radar_rows_since(since):
        score, _ = parse_notes(text(r, "Notes"))
        loc = select(r, "Location")
        tier = tier_for({"location": loc}, loc)
        new.append({"company": text(r, "Company"), "title": text(r, "Role / Title"),
                    "score": score, "fit": select(r, "Fit"), "lane": select(r, "Lane / Category"),
                    "source": select(r, "Source Platform"), "tier": tier, "status": select(r, "Status"),
                    "url": ((r["properties"].get("JD URL") or {}).get("url")) or ""})
    new.sort(key=lambda m: (rank(m["tier"], priority), -m["score"]))
    applied = [{"company": text(r, "Company"), "title": text(r, "Role / Title"),
                "status": select(r, "Status"), "source": select(r, "Source Platform"),
                "radar": text(r, "Notes").startswith("RADAR:")}
               for r in tracker.applied_since(since)]
    all_radar = tracker.feedback_rows()
    statuses = Counter(select(r, "Status") or "?" for r in all_radar)
    labels = Counter(label_for_status(select(r, "Status")) or "open" for r in all_radar)
    cost = spend(settings.costs_path, since, today)
    days_in_month = calendar.monthrange(today.year, today.month)[1]
    pace = cost["mtd"] / today.day * days_in_month if today.day else 0.0

    title = f"Job Radar weekly — {since:%b} {since.day}–{today:%b} {today.day}, {today.year}"
    tiers = Counter(m["tier"] for m in new)
    local_n = sum(is_local(m["tier"]) for m in new)
    lines = [
        f"Window {since.isoformat()} to {today.isoformat()}. Generated by Job Radar (no model calls).",
        "## At a glance",
        f"- New Radar matches: {len(new)} ({local_n} local: Davis/Sacramento area)",
        "- By location: " + (", ".join(f"{LABELS[t]} {n}" for t, n in
                                       sorted(tiers.items(), key=lambda kv: rank(kv[0], priority))) or "none"),
        f"- Applied this week (all sources): {len(applied)} "
        f"({sum(a['radar'] for a in applied)} came from the Radar)",
        f"- Radar spend this week: ${cost['week_total']:.2f} over {cost['runs']} runs"
        + ("" if not cost["by_label"] else " (" + ", ".join(
            f"{k} ${v:.2f}" for k, v in sorted(cost["by_label"].items())) + ")"),
        f"- Month to date: ${cost['mtd']:.2f} of ${settings.monthly_budget_usd:.0f} credit; "
        f"on pace for ${pace:.2f} this month",
        "## New matches (local first)",
    ]
    if not new:
        lines.append("No new matches this week.")
    for m in new[:25]:
        pin = "📍 " if is_local(m["tier"]) else ""
        lines.append(f"- {pin}{m['score']} · {m['company']} — {m['title']} · {LABELS[m['tier']]} · "
                     f"{m['lane'] or '?'} · {m['status']}" + (f" · {m['url']}" if m["url"] else ""))
    if len(new) > 25:
        lines.append(f"…and {len(new) - 25} more in the tracker (filter Notes starts with RADAR:).")
    lines.append("## Applied this week")
    if not applied:
        lines.append("Nothing logged with a Date Applied this week.")
    for a in applied[:40]:
        lines.append(f"- {a['company']} — {a['title']} · {a['status']} · {a['source'] or '?'}"
                     + (" · via Radar" if a["radar"] else ""))
    lines += ["## Feedback loop (all Radar rows)",
              "- " + ", ".join(f"{k} {v}" for k, v in statuses.most_common()),
              f"- Labels the scorer learns from: applied {labels['applied']}, interview "
              f"{labels['interview']}, not interested {labels['skip']}, location skips "
              f"{labels['skip_loc']}, still open {labels['open']}",
              "Tip: set Status to Applied / Skipped – … on Radar rows; the next run uses them as "
              "few-shot examples and the monthly retune uses them to set the cutoff."]
    return title, lines


def run_weekly(settings, write_notion: bool, days: int = 7) -> str:
    from .notion_out import NotionTracker
    tracker = NotionTracker(settings.notion_token, settings.notion_database_id)
    title, lines = build(tracker, settings, days=days)
    settings.reports_dir.mkdir(exist_ok=True)
    md = "\n".join([f"# {title}", ""] + lines) + "\n"
    (settings.reports_dir / f"weekly_{dt.date.today().isoformat()}.md").write_text(md)
    url = ""
    if write_notion:
        url = tracker.create_page(settings.summary_parent_id, title, lines)
    print(md)
    if url:
        print(f"Notion page: {url}")
    return url
